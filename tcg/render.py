"""Validated neutral TestCase models -> stable readable Python source."""
from decimal import Decimal
import re

from . import __version__
from .model import PHASES


def literal(value):
    if type(value) is bool:
        return 'True' if value else 'False'
    if type(value) is int:
        return str(value)
    if type(value) is Decimal and value.is_finite():
        return f"Decimal('{format(value.normalize(), 'f')}')"
    if type(value) is str:
        return repr(value)
    raise ValueError(f'unsupported literal {value!r}')


def function_name(case):
    return f'run_{case.id.lower()}'


def _check_cases(cases, registry):
    identifiers = set()
    for case in cases:
        if case.id in identifiers:
            raise ValueError(f'duplicate case {case.id}')
        identifiers.add(case.id)
        if not re.fullmatch(r'TC_[A-Z0-9_]{1,60}', case.id):
            raise ValueError(f'invalid case id {case.id!r}')
        if not case.steps:
            raise ValueError(f'{case.id}: no steps')
        for step in case.steps:
            contract = registry.get(getattr(step.contract, 'id', None))
            if contract is not step.contract:
                raise ValueError(f'{case.id} {step.execution_id}: operation outside registry')
            if step.phase not in PHASES or step.phase not in contract.phases:
                raise ValueError(f'{case.id} {step.execution_id}: invalid phase')
            if tuple(name for name, _ in step.arguments) != tuple(parameter.name for parameter in contract.parameters):
                raise ValueError(f'{case.id} {step.execution_id}: arguments do not match contract')


def _call(step, alias, method):
    arguments = ''.join(f', {name}={literal(value)}' for name, value in step.arguments)
    return f'log.{method}({literal(step.execution_id)}, {alias}.{step.contract.function.__name__}{arguments})'


def render_python(cases, registry, runner_module):
    cases = tuple(cases)
    _check_cases(cases, registry)
    if not re.fullmatch(r'[A-Za-z_]\w*(?:\.[A-Za-z_]\w*)*', runner_module):
        raise ValueError(f'invalid runner module {runner_module!r}')
    modules = sorted({step.contract.function.__module__ for case in cases for step in case.steps})
    aliases = {module: f'operation_module_{index}' for index, module in enumerate(modules)}
    lines = [
        f'# Generated by tcg {__version__}. Do not edit; change the specification and regenerate.',
        'from decimal import Decimal',
        'from tcg.runtime import StepInfo, TestLog',
    ]
    lines += [f'import {module} as {aliases[module]}' for module in modules]
    lines.append('')
    for case in cases:
        lines += [f'{case.id}_STEPS = (']
        for step in case.steps:
            lines += ['    StepInfo(',
                      f'        execution_id={literal(step.execution_id)},',
                      f'        phase={literal(step.phase)},',
                      f'        test_step={literal(step.test_step) if step.test_step is not None else "None"},',
                      f'        step_name={literal(step.step_name) if step.step_name is not None else "None"},',
                      f'        expectation_order={literal(step.expectation_order) if step.expectation_order is not None else "None"},',
                      f'        source={literal(str(step.source))},',
                      f'        mapping_id={literal(step.mapping_id)},',
                      f'        description={literal(step.description)},',
                      '    ),']
        lines += [')', '', f'def {function_name(case)}(bench):',
                  '    log = TestLog(',
                  f'        test_id={literal(case.id)},',
                  f'        name={literal(case.name)},',
                  f'        objective={literal(case.objective)},',
                  f'        profile_id={literal(case.profile_id)},',
                  f'        steps={case.id}_STEPS,',
                  '        bench=bench,',
                  '    )',
                  '    try:']
        lines += ['        ' + _call(step, aliases[step.contract.function.__module__], 'step')
                  for step in case.steps if step.phase != 'CLEANUP']
        lines += ['    except Exception as error:', '        log.abort(error)', '    finally:']
        lines += ['        ' + _call(step, aliases[step.contract.function.__module__], 'cleanup')
                  for step in case.steps if step.phase == 'CLEANUP']
        lines += ['    return log.finish()', '']
    lines += ['RUNNERS = {']
    lines += [f'    {literal(case.id)}: {function_name(case)},' for case in cases]
    lines += ['}', f'PROFILE_ID = {literal(cases[0].profile_id) if cases else "None"}', '',
              "if __name__ == '__main__':", f'    from {runner_module} import run_main',
              '    raise SystemExit(run_main(PROFILE_ID, RUNNERS))', '']
    return '\n'.join(lines)
