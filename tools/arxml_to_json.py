#!/usr/bin/env python3
"""ARXML to JSON & JSON to ARXML Converter for AUTOSAR Service Interfaces.

A pure Python standard library tool for bidirectional conversion between AUTOSAR
ARXML service descriptions and SpecToTest service definitions (.json). It is the
service-oriented Ethernet counterpart of ``tools/dbc_to_json.py``.

ARXML is a container format, **not a bus type**. This tool deliberately covers one
delimited use case and refuses everything else rather than guessing. The XML parsing
is not duplicated here: it lives with the importer in ``tcg/comm/importers/arxml.py``,
so the compiler and this tool always agree on the supported subset.

Supported:
- AUTOSAR 4.x and 3.x schema namespaces (the detected version is reported).
- SERVICE-INTERFACE with METHODS (CLIENT-SERVER-OPERATION), EVENTS
  (VARIABLE-DATA-PROTOTYPE) and FIELDS (FIELD).
- SOMEIP-SERVICE-INTERFACE-DEPLOYMENT, read only to attach service, method and
  event ids. A service interface without one is valid: SOME/IP is not assumed.

Not supported: ECU extracts, system/topology descriptions, CAN or LIN clusters in
ARXML, frame and PDU mapping, E2E and SecOC properties, data transformation,
compu-methods and PORT-PROTOTYPE wiring. A service interface containing an
unsupported element fails loudly with that element named.
"""

from __future__ import annotations

import argparse
import json
from pathlib import Path
import re
import sys
from typing import Any
from xml.sax.saxutils import escape

if __package__ in (None, ''):  # allow `python tools/arxml_to_json.py`
    sys.path.insert(0, str(Path(__file__).resolve().parent.parent))

from tcg.comm.importers.arxml import parse_arxml, resources_from_arxml  # noqa: E402
from tcg.comm.model import ObjectKind  # noqa: E402
from tcg.core.model import SpecError  # noqa: E402

AUTOSAR_NAMESPACE = 'http://autosar.org/schema/r4.0'
SHORT_NAME = re.compile(r'[A-Za-z_][A-Za-z0-9_]*')

#: SOME/IP identifier ranges (AUTOSAR SOME/IP protocol specification).
MAX_SERVICE_ID = 0xFFFE
MAX_METHOD_ID = 0x7FFF
MIN_EVENT_ID = 0x8000
MAX_EVENT_ID = 0xFFFF


def _int_or_none(value: Any) -> int | None:
    if value is None or value == '':
        return None
    try:
        return int(str(value), 0)
    except (TypeError, ValueError):
        return None


def arxml_to_dict(arxml_content: str, name: str = 'description.arxml') -> dict[str, Any]:
    """Parse an ARXML service description into a SpecToTest dictionary.

    Args:
        arxml_content: Raw text content of an .arxml file.
        name: File name used in error messages.

    Returns:
        Dictionary with database, autosar_version and services.
    """
    root = parse_arxml(arxml_content, name)
    resources, version = resources_from_arxml(root, network=Path(name).stem, source=name)

    services: dict[str, Any] = {}
    for resource in resources:
        if resource.kind is not ObjectKind.SERVICE:
            continue
        attributes = dict(resource.attributes)
        services[resource.name] = {
            'service_id': _int_or_none(attributes.get('service_id')),
            'someip': bool(attributes.get('someip')),
            'methods': {},
            'events': {},
            'fields': {},
        }

    bucket_for = {
        ObjectKind.METHOD: 'methods',
        ObjectKind.EVENT: 'events',
        ObjectKind.FIELD: 'fields',
    }
    for resource in resources:
        bucket = bucket_for.get(resource.kind)
        if bucket is None:
            continue
        service = services.get(resource.container)
        if service is None:  # a member without its interface cannot happen, but be safe
            continue
        attributes = dict(resource.attributes)
        entry: dict[str, Any] = {}
        identifier = _int_or_none(attributes.get('id'))
        if identifier is not None:
            entry['id'] = identifier
        if attributes.get('data_type'):
            entry['data_type'] = attributes['data_type']
        service[bucket][resource.name] = entry

    return {
        'database': Path(name).stem,
        'protocol': 'Ethernet',
        'autosar_version': version,
        'services': services,
    }


def dict_to_arxml(data: dict[str, Any]) -> str:
    """Render a SpecToTest service dictionary back into ARXML text."""
    services = data.get('services') or {}
    lines = [
        '<?xml version="1.0" encoding="UTF-8"?>',
        '<!-- Generated by tools/arxml_to_json.py. Edit the JSON and regenerate. -->',
        f'<AUTOSAR xmlns="{AUTOSAR_NAMESPACE}">',
        '  <AR-PACKAGES>',
        '    <AR-PACKAGE>',
        '      <SHORT-NAME>Services</SHORT-NAME>',
        '      <ELEMENTS>',
    ]

    for service_name, service in services.items():
        lines.append('        <SERVICE-INTERFACE>')
        lines.append(f'          <SHORT-NAME>{escape(service_name)}</SHORT-NAME>')
        for bucket, container, element in (
            ('methods', 'METHODS', 'CLIENT-SERVER-OPERATION'),
            ('events', 'EVENTS', 'VARIABLE-DATA-PROTOTYPE'),
            ('fields', 'FIELDS', 'FIELD'),
        ):
            members = service.get(bucket) or {}
            if not members:
                continue
            lines.append(f'          <{container}>')
            for member_name, member in members.items():
                lines.append(f'            <{element}>')
                lines.append(f'              <SHORT-NAME>{escape(member_name)}</SHORT-NAME>')
                data_type = (member or {}).get('data_type')
                if data_type:
                    lines.append(
                        '              <TYPE-TREF DEST="APPLICATION-PRIMITIVE-DATA-TYPE">'
                        f'/DataTypes/{escape(str(data_type))}</TYPE-TREF>')
                lines.append(f'            </{element}>')
            lines.append(f'          </{container}>')
        lines.append('        </SERVICE-INTERFACE>')

    lines += ['      </ELEMENTS>', '    </AR-PACKAGE>']

    deployed = {name: service for name, service in services.items()
                if service.get('someip') or service.get('service_id') is not None}
    if deployed:
        lines += ['    <AR-PACKAGE>', '      <SHORT-NAME>Deployment</SHORT-NAME>',
                  '      <ELEMENTS>']
        for service_name, service in deployed.items():
            lines.append('        <SOMEIP-SERVICE-INTERFACE-DEPLOYMENT>')
            lines.append(f'          <SHORT-NAME>{escape(service_name)}</SHORT-NAME>')
            if service.get('service_id') is not None:
                lines.append(f'          <SERVICE-INTERFACE-ID>{service["service_id"]}'
                             f'</SERVICE-INTERFACE-ID>')
            for bucket, container, element, ref, id_tag in (
                ('methods', 'METHOD-DEPLOYMENTS', 'SOMEIP-METHOD-DEPLOYMENT',
                 'METHOD-REF', 'METHOD-ID'),
                ('events', 'EVENT-DEPLOYMENTS', 'SOMEIP-EVENT-DEPLOYMENT',
                 'EVENT-REF', 'EVENT-ID'),
            ):
                members = {name: member for name, member in (service.get(bucket) or {}).items()
                           if (member or {}).get('id') is not None}
                if not members:
                    continue
                lines.append(f'          <{container}>')
                for member_name, member in members.items():
                    lines.append(f'            <{element}>')
                    lines.append(
                        f'              <{ref}>/Services/{escape(service_name)}/'
                        f'{escape(member_name)}</{ref}>')
                    lines.append(f'              <{id_tag}>{member["id"]}</{id_tag}>')
                    lines.append(f'            </{element}>')
                lines.append(f'          </{container}>')
            lines.append('        </SOMEIP-SERVICE-INTERFACE-DEPLOYMENT>')
        lines += ['      </ELEMENTS>', '    </AR-PACKAGE>']

    lines += ['  </AR-PACKAGES>', '</AUTOSAR>']
    return '\n'.join(lines) + '\n'


def validate_service_database(data: dict[str, Any]) -> list[str]:
    """Validate a service dictionary against AUTOSAR / SOME/IP constraints.

    Checks:
    - Short names are valid identifiers.
    - A service declares at least one method, event or field.
    - SOME/IP id ranges: service <= 0xFFFE, method <= 0x7FFF, event 0x8000..0xFFFF.
    - Duplicate method or event ids within one service.
    - A service marked as SOME/IP but carrying no service id.
    - Member ids declared while the service has no SOME/IP deployment.

    Returns:
        List of error strings (empty list if compliant).
    """
    errors: list[str] = []
    services = data.get('services') or {}
    if not isinstance(services, dict):
        return ["'services' must be an object"]

    seen_service_ids: dict[int, str] = {}
    for service_name, service in services.items():
        if not SHORT_NAME.fullmatch(str(service_name)):
            errors.append(f"Service '{service_name}' is not a valid AUTOSAR SHORT-NAME")
        if not isinstance(service, dict):
            errors.append(f"Service '{service_name}' must be an object")
            continue

        methods = service.get('methods') or {}
        events = service.get('events') or {}
        fields = service.get('fields') or {}
        if not methods and not events and not fields:
            errors.append(f"Service '{service_name}' declares no methods, events or fields")

        service_id = service.get('service_id')
        someip = bool(service.get('someip'))
        if service_id is not None:
            if not isinstance(service_id, int) or not 0 <= service_id <= MAX_SERVICE_ID:
                errors.append(f"Service '{service_name}' id {service_id!r} is outside "
                              f"0..0x{MAX_SERVICE_ID:04X}")
            elif service_id in seen_service_ids:
                errors.append(f"Service '{service_name}' reuses service id {service_id} "
                              f"of '{seen_service_ids[service_id]}'")
            else:
                seen_service_ids[service_id] = service_name
        elif someip:
            errors.append(f"Service '{service_name}' is marked as SOME/IP but has no "
                          f"service id")

        for bucket, members, low, high in (
            ('method', methods, 0, MAX_METHOD_ID),
            ('event', events, MIN_EVENT_ID, MAX_EVENT_ID),
        ):
            seen_ids: dict[int, str] = {}
            for member_name, member in members.items():
                if not SHORT_NAME.fullmatch(str(member_name)):
                    errors.append(f"Service '{service_name}': {bucket} '{member_name}' "
                                  f"is not a valid AUTOSAR SHORT-NAME")
                identifier = (member or {}).get('id')
                if identifier is None:
                    continue
                if service_id is None:
                    errors.append(f"Service '{service_name}': {bucket} '{member_name}' "
                                  f"declares id {identifier} but the service has no "
                                  f"SOME/IP deployment")
                if not isinstance(identifier, int) or not low <= identifier <= high:
                    errors.append(f"Service '{service_name}': {bucket} '{member_name}' "
                                  f"id {identifier!r} is outside 0x{low:04X}..0x{high:04X}")
                elif identifier in seen_ids:
                    errors.append(f"Service '{service_name}': {bucket} '{member_name}' "
                                  f"reuses id {identifier} of '{seen_ids[identifier]}'")
                else:
                    seen_ids[identifier] = member_name

        for field_name in fields:
            if not SHORT_NAME.fullmatch(str(field_name)):
                errors.append(f"Service '{service_name}': field '{field_name}' is not "
                              f"a valid AUTOSAR SHORT-NAME")

    return errors


def convert_file(
    input_path: Path,
    output_path: Path | None = None,
    force_mode: str | None = None,
    pretty: bool = True,
    check: bool = False,
) -> tuple[dict[str, Any] | str, list[str]]:
    """Convert ARXML to JSON or JSON to ARXML, optionally writing to output_path.

    Args:
        input_path: Path to source file (.arxml/.xml or .json).
        output_path: Path to target file (or None for in-memory return).
        force_mode: 'json' or 'arxml' to override extension inference.
        pretty: Whether to format JSON with indentation.
        check: Whether to perform validation checks.

    Returns:
        Tuple of (result_data_or_string, list_of_validation_issues).
    """
    content = input_path.read_text(encoding='utf-8-sig')
    ext = input_path.suffix.lower()

    if force_mode == 'arxml' or (force_mode is None and ext == '.json'):
        # JSON -> ARXML
        data = json.loads(content)
        validation_issues = validate_service_database(data) if check else []
        result: dict[str, Any] | str = dict_to_arxml(data)
        if output_path:
            output_path.parent.mkdir(parents=True, exist_ok=True)
            output_path.write_text(result, encoding='utf-8')
        return result, validation_issues

    # Default: ARXML -> JSON
    data = arxml_to_dict(content, input_path.name)
    validation_issues = validate_service_database(data) if check else []
    if output_path:
        output_path.parent.mkdir(parents=True, exist_ok=True)
        with open(output_path, 'w', encoding='utf-8') as handle:
            if pretty:
                json.dump(data, handle, indent=2, ensure_ascii=False)
                handle.write('\n')
            else:
                json.dump(data, handle, ensure_ascii=False)
    return data, validation_issues


def main() -> int:
    """CLI entrypoint for the arxml_to_json converter."""
    parser = argparse.ArgumentParser(
        description='AUTOSAR ARXML service interfaces <-> SpecToTest JSON Converter & Validator.',
        formatter_class=argparse.RawDescriptionHelpFormatter,
        epilog="""
Examples:
  # Convert ARXML to JSON and validate:
  python tools/arxml_to_json.py tools/vehicle_services.arxml -o inputs/eth_services.json --check

  # Validate only, without writing anything:
  python tools/arxml_to_json.py tools/vehicle_services.arxml --check

  # Regenerate an ARXML from JSON:
  python tools/arxml_to_json.py inputs/eth_services.json -o out/vehicle_services.arxml

Only SERVICE-INTERFACE elements are supported; see the module docstring for the
full list of unsupported AUTOSAR constructs.
""")
    parser.add_argument('input', type=Path, help='Source .arxml/.xml or .json file')
    parser.add_argument('-o', '--output', type=Path, default=None,
                        help='Target file (omit to print a summary only)')
    parser.add_argument('--mode', choices=('json', 'arxml'), default=None,
                        help='Force the conversion direction')
    parser.add_argument('--check', action='store_true',
                        help='Validate the service database and report issues')
    parser.add_argument('--compact', action='store_true',
                        help='Write JSON without indentation')
    args = parser.parse_args()

    if not args.input.is_file():
        print(f'CONVERSION FAILED: input file not found: {args.input}', file=sys.stderr)
        return 2
    try:
        result, issues = convert_file(args.input, args.output, args.mode,
                                      pretty=not args.compact, check=args.check)
    except SpecError as error:
        print(f'CONVERSION FAILED: {error}', file=sys.stderr)
        return 2
    except (OSError, json.JSONDecodeError, ValueError) as error:
        print(f'CONVERSION FAILED: {args.input.name}: {error}', file=sys.stderr)
        return 2

    if isinstance(result, dict):
        services = result.get('services', {})
        members = sum(len(service.get(bucket, {}))
                      for service in services.values()
                      for bucket in ('methods', 'events', 'fields'))
        print(f'Service database "{result.get("database")}" '
              f'(AUTOSAR {result.get("autosar_version")}): '
              f'{len(services)} service(s), {members} member(s)')
    else:
        print(f'Rendered ARXML: {len(result.splitlines())} lines')
    if args.output:
        print(f'Written to: {args.output}')

    if args.check:
        if issues:
            print(f'\nValidation found {len(issues)} issue(s):', file=sys.stderr)
            for issue in issues:
                print(f'  - {issue}', file=sys.stderr)
            return 1
        print('Validation: no issues found')
    return 0


if __name__ == '__main__':
    raise SystemExit(main())
